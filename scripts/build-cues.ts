import fs from 'node:fs';
import path from 'node:path';
import { parseLrc } from '../src/lib/lrc';

const lrcPath = path.resolve(__dirname, '../public/song.lrc');
const outPath = path.resolve(__dirname, '../src/data/cues.generated.ts');

const src = fs.readFileSync(lrcPath, 'utf-8');
const cues = parseLrc(src);

const content = `// Generated by scripts/build-cues.ts. Do not edit by hand.
import type { Cue } from '../lib/lrc';

export const CUES: Cue[] = ${JSON.stringify(cues, null, 2)};
`;

fs.writeFileSync(outPath, content, 'utf-8');
console.log(`Generated ${cues.length} cues in src/data/cues.generated.ts`);
